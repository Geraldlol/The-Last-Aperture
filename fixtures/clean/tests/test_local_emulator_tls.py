#   `verify=False` as Critical.
#
# Why it is not a finding:
#   The discriminator crypto-and-key-management insists on is the HOST LITERAL AT
#   THE CALL SITE, not the directory. So it is written at every call site, three
#   times, and it is a loopback address with a fixed port that the fixture itself
#   starts:
#
#       https://127.0.0.1:4443        (the emulator this module launches)
#
#   The certificate is generated by `local_emulator.start()` into a temp dir at
#   test time and thrown away at teardown, so there is no CA to trust and nothing
#   for a pin to pin. No value here is read from configuration, no environment
#   variable can retarget the host, and there is no import of this module from any
#   non-test path — the file is a pytest module, its only symbols are fixtures and
#   `test_*` functions, and it imports nothing from the application except the
#   client under test.
#
#   What deliberately does NOT appear, because none of it would clear anything:
#   no "it's internal", no "there's a mesh", no "it's behind the VPN", and no
#   `NODE_TLS_REJECT_UNAUTHORIZED` or `urllib3.disable_warnings()` hiding a
#   second, non-local disable elsewhere in the file.
#
# False-positive entries exercised:
#   ai-generated-code (4)          `verify=False` against a local fixture, with
#                                  the host literal at the call site
#   ai-generated-code (13)         a security test's own fixtures, exempted by an
