#                                  makes this clean; the host literal is

from __future__ import annotations

import pytest
import requests

from . import local_emulator

# Loopback, fixed port, started by this module. Written as a literal so the
# discriminator is at the call site and not in a settings file.
EMULATOR_BASE = "https://127.0.0.1:4443"


@pytest.fixture(scope="module")
def emulator():
    """Start the receipt-validation emulator on loopback with a throwaway cert."""
    handle = local_emulator.start(host="127.0.0.1", port=4443)
    try:
        yield handle
    finally:
        handle.stop()


def test_emulator_accepts_a_well_formed_receipt(emulator):
    # verify=False against https://127.0.0.1:4443 — the emulator's certificate is
    # self-signed and regenerated per run, so there is no trust anchor to install.
    response = requests.post(
        "https://127.0.0.1:4443/v1/receipts",
        json={"receipt": "AAAA", "product": "notes.pro.monthly"},
        timeout=5,
        verify=False,
    )
    assert response.status_code == 200
    assert response.json()["status"] == "valid"


def test_emulator_rejects_a_replayed_receipt(emulator):
    body = {"receipt": "BBBB", "product": "notes.pro.monthly"}

    first = requests.post(
        "https://127.0.0.1:4443/v1/receipts", json=body, timeout=5, verify=False
    )
    assert first.status_code == 200

    replay = requests.post(
        "https://127.0.0.1:4443/v1/receipts", json=body, timeout=5, verify=False
    )
    assert replay.status_code == 409


def test_production_client_does_not_disable_verification():
    """The control test for the file above.

    A test module that turns verification off is only acceptable while the
    shipped client leaves it on, so that is asserted here rather than assumed.
    `requests` defaults `verify` to True; this pins the default against a future
    edit that adds a `verify=` kwarg to the session builder.
    """
    from application.receipts import build_session

    session = build_session(base_url=EMULATOR_BASE)
    assert session.verify is True
    assert session.trust_env is False
